"""Generate the gzipped web UI header. Run directly: python3 tools/web_assets.py"""
import gzip, hashlib, io, os

FILES = ["index.html", "app.js", "record.js", "take.js", "scriptview.js", "blocks.js", "words.js", "style.css", "icon.svg", "manifest.webmanifest"]
TYPES = {"html": "text/html; charset=utf-8", "js": "text/javascript; charset=utf-8", "css": "text/css; charset=utf-8",
         "svg": "image/svg+xml", "webmanifest": "application/manifest+json"}


def gz(data):
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode="wb", compresslevel=9, mtime=0, filename="") as f:
        f.write(data)
    return out.getvalue()


def generate(project):
    web = os.path.normpath(os.path.join(project, "..", "web"))
    dst = os.path.join(project, "lib", "proptroller", "src", "proptroller", "web_assets.h")
    lines = ["// Generated by tools/web_assets.py from firmware/web: do not edit.",
             "// The phone web UI, gzipped (served with Content-Encoding: gzip).", "#pragma once",
             "#include <stddef.h>", "#include <stdint.h>", "namespace pt {", "struct WebAsset {",
             "  const char* path;", "  const char* type;", "  const uint8_t* gz;", "  size_t gz_len;",
             "  size_t raw_len;", "  const char* etag;  // a hash of the gzipped bytes, quoted (HTTP ETag)", "};"]
    entries = []
    for i, name in enumerate(FILES):
        raw = open(os.path.join(web, name), "rb").read()
        z = gz(raw)
        body = ",".join("0x%02x" % b for b in z)
        rows = [body[k:k + 120] for k in range(0, len(body), 120)]
        lines.append("static const uint8_t WEB_%d[] = {" % i)
        lines.extend(rows)
        lines.append("};")
        etag = '\\"%s\\"' % hashlib.sha256(z).hexdigest()[:16]
        entries.append('  {"/%s", "%s", WEB_%d, %d, %d, "%s"},' % (name, TYPES[name.rsplit(".", 1)[1]], i, len(z), len(raw), etag))
    lines.append("static const WebAsset WEB_ASSETS[] = {")
    lines.extend(entries)
    lines.append("};")
    lines.append("static const size_t WEB_ASSET_COUNT = %d;" % len(FILES))
    lines.append("}  // namespace pt")
    text = "\n".join(lines) + "\n"
    old = open(dst).read() if os.path.exists(dst) else None
    if old != text:
        with open(dst, "w") as f:
            f.write(text)


if __name__ == "__main__":
    generate(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
