# PlatformIO pre-build step of the Pico W / Pico 2 W firmware environments (picow, pico2w): link the firmware to run from
# the active slot behind the Pico bootloader (PICO-BOOTLOADER.md) instead of from the start of flash.
#
# The linker script is made at build time from the installed arduino-pico core's own memmap_default.ld (nothing
# from the core is copied into this repository):
#   * FLASH starts at the active slot (0x10007000) and is as long as the slot, so an image that does not fit
#     fails to link;
#   * the sections arduino-pico puts in front of the sketch go: boot2 (the bootloader carries it), the OTA loader
#     (ota.o: the bootloader replaces it) and its partition record; their input sections are discarded so the
#     linker cannot place them as orphans in front of the vector table;
#   * LittleFS and the EEPROM sector are where picoboot_map.h puts them (board_build.filesystem_size = 188k
#     gives the same numbers to arduino-pico's FS_START / FS_END defines; tools/picoboot_check.py compares).
import inspect
import os
import re

Import("env")  # noqa: F821

# firmware/arduino, from this script's own place (PlatformIO runs it with exec: no __file__); a project of its own
# (workspace-template/) uses this script by path
TOOLS = os.path.dirname(os.path.abspath(inspect.getframeinfo(inspect.currentframe()).filename))
PROJ = os.path.dirname(TOOLS)
board = env.BoardConfig()  # noqa: F821
chip = board.get("build.mcu")


def map_values():
    text = open(os.path.join(PROJ, "lib", "proptroller", "src", "proptroller", "picoboot_map.h")).read()
    vals = {}
    for name, value in re.findall(r"#define PICOBOOT_(\w+) (0x[0-9A-Fa-f]+)u", text):
        vals[name] = int(value, 16)
    return vals


def make_script():
    m = map_values()
    key = "RP2350" if chip == "rp2350" else "RP2040"
    flash = m[key + "_FLASH"]
    active_len = m[key + "_ACTIVE_LEN"]
    origin = m["XIP_BASE"] + m["ACTIVE_OFFSET"]
    fs_start = m["XIP_BASE"] + flash - m["EEPROM_LEN"] - m["FS_LEN"]
    fs_end = m["XIP_BASE"] + flash - m["EEPROM_LEN"]
    fw = env.PioPlatform().get_package_dir("framework-arduinopico")  # noqa: F821
    src = open(os.path.join(fw, "lib", chip, "memmap_default.ld")).read()

    def drop(pattern, what):
        nonlocal src
        new, n = re.subn(pattern, "\n", src, flags=re.S)
        if n != 1:
            raise SystemExit("picoboot_ld.py: arduino-pico's memmap_default.ld changed (%s not found once)" % what)
        src = new

    # FLASH: the active slot
    new, n = re.subn(r"FLASH\(rx\) : ORIGIN = 0x10000000, LENGTH = __FLASH_LENGTH__",
                     "FLASH(rx) : ORIGIN = 0x%08X, LENGTH = 0x%X" % (origin, active_len), src)
    if n != 1:
        raise SystemExit("picoboot_ld.py: FLASH region of memmap_default.ld not found")
    src = new
    if chip == "rp2040":
        drop(r"\n[ \t]*\.boot2 : \{.*?\} > FLASH\s*ASSERT\(__boot2_end__ - __boot2_start__ == 256,.*?\)[ \t]*\n", ".boot2")
    drop(r"\n[ \t]*\.ota : \{.*?\} > FLASH[ \t]*\n", ".ota")
    drop(r"\n[ \t]*\.partition : \{.*?\} > FLASH[ \t]*\n", ".partition")
    discard = ("\n    /* behind the Pico bootloader: no boot2, no OTA loader (tools/picoboot_ld.py) */\n"
               "    /DISCARD/ : { *(.boot2) *(.OTA) *ota.o(*) }\n")
    src = src.replace("SECTIONS\n{", "SECTIONS\n{" + discard, 1)
    for k, v in (("__EEPROM_START__", fs_end), ("__FS_START__", fs_start), ("__FS_END__", fs_end)):
        src = src.replace(k, "0x%08X" % v)
    src = src.replace("__FLASH_LENGTH__", "0x%X" % active_len)
    psram = int(board.get("upload.psram_length", "0"))
    ram = board.get("upload.maximum_ram_size")
    src = src.replace("__RAM_LENGTH__", "%dk" % (int(ram) // 1024)).replace("__PSRAM_LENGTH__", "%d" % psram)
    header = ("/* Generated by tools/picoboot_ld.py from arduino-pico's %s/memmap_default.ld: the firmware in the\n"
              "   active slot behind the Pico bootloader (lib/proptroller/src/proptroller/picoboot_map.h). */\n" % chip)
    out = os.path.join(env.subst("$BUILD_DIR"), "memmap_picoboot.ld")  # noqa: F821
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(header + src)
    return out


script = make_script()
board.update("build.ldscript", script)
env.Replace(LDSCRIPT_PATH=script)  # noqa: F821
env.Append(CPPDEFINES=["PT_PICOBOOT"])  # noqa: F821


def check(target, source, env):  # noqa: ARG001
    import subprocess
    import sys
    board_name = "pico2-w" if chip == "rp2350" else "pico-w"
    r = subprocess.run([sys.executable, os.path.join(TOOLS, "picoboot_image.py"), "check-app", env.subst("$PIOENV"),
                        "--app-build", os.path.dirname(env.subst("$BUILD_DIR")), "--board", board_name])
    if r.returncode != 0:
        env.Exit(1)


env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", check)  # noqa: F821
